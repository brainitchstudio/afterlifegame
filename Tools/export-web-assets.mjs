// Copies the Unity presentation assets into the React/Python web build so both front ends share
// one source of art and styling:
//   Assets/Afterlife/Resources/{AfterlifeAtlas.png,.json, UI/, Title/, Buildings/, ThirdPartyNotices.txt}
//     -> web/public/unity/
//   Assets/Afterlife/Resources/Afterlife.uss -> web/src/hud/afterlife.css (USS converted to CSS)
// Run with `node Tools/export-web-assets.mjs`; pass --check to fail when the web copies are stale.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const resources = path.join(root, 'Assets/Afterlife/Resources');
const publicOut = path.join(root, 'web/public/unity');
const cssOut = path.join(root, 'web/src/hud/afterlife.css');
const check = process.argv.includes('--check');
const stale = [];

function write(target, data) {
  const current = fs.existsSync(target) ? fs.readFileSync(target) : null;
  if (current && Buffer.compare(current, Buffer.from(data)) === 0) return;
  if (check) { stale.push(path.relative(root, target)); return; }
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, data);
}

const copy = (from, to) => write(to, fs.readFileSync(from));
for (const file of ['AfterlifeAtlas.png', 'AfterlifeAtlas.json', 'ThirdPartyNotices.txt'])
  copy(path.join(resources, file), path.join(publicOut, file));
const spriteNames = {};
for (const dir of ['UI', 'Title', 'Buildings', 'FX']) {
  const files = fs.readdirSync(path.join(resources, dir)).filter(f => f.endsWith('.png')).sort();
  for (const file of files) copy(path.join(resources, dir, file), path.join(publicOut, dir, file));
  spriteNames[dir] = files.map(f => f.slice(0, -4));
}
// Pixel generators the web HUD runs directly (the Supplies Card draws its parts at runtime).
for (const file of ['pixel-supplies.js'])
  copy(path.join(root, 'Tools/ArtSource/ui-kit', file), path.join(root, 'web/src/hud/kit', file));

// The HUD resolves sprites the way GameHud.GetSprite does (UI/ first, then Buildings/), so it needs
// to know which names exist without probing the server.
write(path.join(root, 'web/src/hud/uiSprites.json'), JSON.stringify(spriteNames, null, 1) + '\n');

// USS is a CSS dialect. Unity-only properties are mapped to their CSS equivalents and the
// UI Toolkit element defaults (flex columns, solid borders, no text wrap) are restated up front.
const TEXT_ALIGN = { left: 'left', center: 'center', right: 'right' };
const VERTICAL = { upper: 'flex-start', middle: 'center', lower: 'flex-end' };
const SCALE_MODE = { 'stretch-to-fill': '100% 100%', 'scale-to-fit': 'contain', 'scale-and-crop': 'cover' };
function convertDeclarations(body) {
  const hasJustify = /(^|[;\s])justify-content\s*:/.test(body);
  return body
    .replace(/-unity-font-style\s*:\s*([a-z-]+)\s*;/g, (_, style) =>
      style === 'bold' ? 'font-weight: 700;' : style === 'italic' ? 'font-style: italic;' : style === 'bold-and-italic' ? 'font-weight: 700; font-style: italic;' : 'font-weight: 400; font-style: normal;')
    .replace(/-unity-text-align\s*:\s*([a-z]+)-([a-z]+)\s*;/g, (_, v, h) =>
      `text-align: ${TEXT_ALIGN[h]};` + (hasJustify ? '' : ` justify-content: ${VERTICAL[v]};`))
    .replace(/-unity-background-scale-mode\s*:\s*([a-z-]+)\s*;/g, (_, mode) => `background-size: ${SCALE_MODE[mode] || '100% 100%'};`)
    .replace(/-unity-[a-z-]+\s*:[^;]*;/g, '')
    // UI Toolkit text always honours line breaks; normal additionally wraps.
    .replace(/white-space\s*:\s*normal\s*;/g, 'white-space: pre-wrap;')
    .replace(/white-space\s*:\s*nowrap\s*;/g, 'white-space: pre;')
    .replace(/\bscale\s*:\s*([0-9.]+)\s*;/g, 'transform: scale($1);');
}
const uss = fs.readFileSync(path.join(resources, 'Afterlife.uss'), 'utf8');
const converted = uss
  .replace(/\.unity-scroller--vertical[^{]*\{[^}]*\}/g, '')
  .replace(/\{([^}]*)\}/g, (_, body) => '{' + convertDeclarations(body) + '}')
  // Type selectors refer to UI Toolkit controls; the web HUD renders them as <button>.
  .replace(/(^|[\s,])Button\b/g, '$1button');

const prelude = `/* Generated by Tools/export-web-assets.mjs from Assets/Afterlife/Resources/Afterlife.uss. Do not edit. */
/* UI Toolkit defaults, at zero specificity so every USS rule overrides them: each element is a
   flex column with solid borders, and text keeps its line breaks but only wraps when a rule asks. */
:where(.hud-root, .hud-root *) { box-sizing: border-box; border-style: solid; border-width: 0; border-color: transparent; }
:where(.hud-root div, .hud-root button) { display: flex; flex-direction: column; position: relative; flex-shrink: 1; }
:where(.hud-root .ui-label, .hud-root button) { white-space: pre; }
:where(.hud-root button) { font: inherit; color: inherit; cursor: pointer; text-align: left; justify-content: center; }
:where(.hud-root button:disabled) { cursor: default; }
:where(.hud-root .ui-sprite) { background-repeat: no-repeat; background-position: center; background-size: 100% 100%; image-rendering: pixelated; }
:where(.hud-root .ui-scroll) { overflow-x: hidden; overflow-y: auto; flex-shrink: 1; min-height: 0; scrollbar-width: thin; scrollbar-color: #3e4f35 #1a2216; }
/* A ScrollView's content container takes its content's natural height instead of shrinking to fit. */
:where(.hud-root .ui-scroll > *) { flex-shrink: 0; }
.hud-root .ui-scroll::-webkit-scrollbar { width: 6px; }
.hud-root .ui-scroll::-webkit-scrollbar-track { background-color: #1a2216; border-radius: 3px; }
.hud-root .ui-scroll::-webkit-scrollbar-thumb { background-color: #3e4f35; border-radius: 3px; }
.hud-root .ui-scroll::-webkit-scrollbar-thumb:hover { background-color: #617951; }
`;
write(cssOut, prelude + converted);

if (check && stale.length) {
  console.error('Web assets are stale; run node Tools/export-web-assets.mjs\n  ' + stale.join('\n  '));
  process.exit(1);
}
console.log(check ? 'Web assets are current.' : 'Exported Unity assets to web/public/unity and web/src/hud/afterlife.css');
